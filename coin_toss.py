# BRIEF DESCRIPTION: This program simulates a coin flip.
# A random number between 1 and 100 is generated.
# If the number is 51 or greater, Tails is printed.
# Otherwise, Heads is printed.
 

import random

number = random.randint(1, 100)

if number >= 51:
    print("Tails")
else:
    print("Heads")










